const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const html = fs.readFileSync(path.join(__dirname, '../www/mobile/index.html'), 'utf8');
// Frappe website rendering expands the reserved {index} directory placeholder.
assert(!html.includes('${index}'));
const script = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].find(m => m[1].includes('function soluaDeliveryMapRoutes'))[1];
const context = {URLSearchParams};
vm.createContext(context);
vm.runInContext(script.split('(() => {')[0], context);
const routes = context.soluaDeliveryMapRoutes(['A & B', 'C', 'D', 'E', 'F', 'G'], 'Warehouse');
assert.equal(routes.length, 2);
assert.equal(new URL(routes[0].url).searchParams.get('origin'), 'Warehouse');
assert.equal(new URL(routes[0].url).searchParams.get('waypoints'), 'A & B|C|D');
assert.equal(new URL(routes[0].url).searchParams.get('destination'), 'E');
assert.equal(new URL(routes[1].url).searchParams.get('origin'), 'E');
assert.equal(new URL(routes[1].url).searchParams.get('destination'), 'G');
assert.equal(new URL(context.soluaDeliveryMapRoutes(['Maputo'])[0].url).searchParams.has('origin'), false);
assert.throws(() => context.soluaDeliveryMapRoutes([]));
assert.throws(() => context.soluaDeliveryMapRoutes(['']));
assert.throws(() => context.soluaDeliveryMapRoutes(['x'.repeat(2100)]));
assert(context.soluaDeliveryMapRoutes(['地址'.repeat(50), '地点'.repeat(50), '位置'.repeat(50)]).every(route => route.url.length <= 2048));
assert.throws(() => context.soluaDeliveryMapRoutes(['地址'.repeat(100), '地址'.repeat(100)]));
const returnRoute = context.soluaDeliveryMapRoutes(['A', 'B'], 'Warehouse', true);
assert.equal(new URL(returnRoute[0].url).searchParams.get('destination'), 'Warehouse');
assert.equal(new URL(returnRoute[0].url).searchParams.get('waypoints'), 'A|B');
assert.throws(() => context.soluaDeliveryMapRoutes(['A'], '', true));
console.log('mobile delivery route checks passed');
